"""Build the Debug Console font atlas and AS2 glyph table from this repository.

Input:   resources/font/eid_default.fnt (+ pages)   EID's bitmap font (BMFont v3 binary)
Outputs (into <out_dir>):
  dcon_atlas.png       packed glyphs of printable ASCII (embedded into the SWF as a bitmap)
  dcon_data.as         AS2 glyph table
"""
import os
import struct
import sys

from PIL import Image

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
FONT = os.path.join(REPO, "resources", "font", "eid_default.fnt")


def parse_fnt(path):
    d = open(path, "rb").read()
    assert d[:4] == b"BMF\x03", "expected binary BMFont v3"
    p, chars, common, pages = 4, {}, None, []
    while p < len(d):
        t, size = d[p], struct.unpack("<I", d[p + 1:p + 5])[0]
        b = d[p + 5:p + 5 + size]
        p += 5 + size
        if t == 2:
            common = struct.unpack("<HH", b[:4])  # lineHeight, base
        elif t == 3:
            pages = [x.decode() for x in b.split(b"\0") if x]
        elif t == 4:
            for i in range(0, size, 20):
                cid, x, y, w, h, xo, yo, xa, pg, _ = struct.unpack("<IHHHHhhhBB", b[i:i + 20])
                chars[cid] = (x, y, w, h, xo, yo, xa, pg)
    return chars, common, pages


def build(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    chars, (line_height, base), pages = parse_fnt(FONT)
    page_imgs = [Image.open(os.path.join(os.path.dirname(FONT), p)).convert("RGBA") for p in pages]
    glyphs, lines = [], []
    x = y = row = 0
    for c in range(32, 127):
        g = chars.get(c)
        if g is None:
            print("warning: font has no glyph for", repr(chr(c)))
            continue
        gx, gy, w, h, xo, yo, xa, pg = g
        ax = ay = 0
        if w and h:
            if x + w + 1 > 256:
                x, y, row = 0, y + row + 1, 0
            ax, ay = x, y
            glyphs.append((page_imgs[pg].crop((gx, gy, gx + w, gy + h)), (ax, ay)))
            x += w + 1
            row = max(row, h)
        lines.append(f"G[{c}]=[{ax},{ay},{w},{h},{xo},{yo},{xa}];")
    atlas = Image.new("RGBA", (256, y + row + 1), (0, 0, 0, 0))
    for img, pos in glyphs:
        atlas.paste(img, pos)
    atlas.save(os.path.join(out_dir, "dcon_atlas.png"))
    out = ["// GENERATED by flash/tools/dcon_assets.py from the EID font. Do not edit.",
           f"_root.dconLineHeight = {line_height};",
           "var G = _root.dconGlyph = [];", *lines]
    open(os.path.join(out_dir, "dcon_data.as"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"atlas {atlas.size}, {len(lines)} glyphs")


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "flash", "build"))
